-- Requires the complete v1 schema, including search_vector_generation.
-- Oracle DDL commits implicitly: take a backup; do not blindly rerun after failure.
-- This retains old tables; it is NOT a finished application cutover.
-- Deploy v2 JDBC code together with finalization; cache copies become stale if v1 writes resume.
-- Reconcile again under maintenance before deploying v2 code.

CREATE TABLE search_user_vector (
 user_id VARCHAR2(64) PRIMARY KEY,
 revision NUMBER(19) DEFAULT 0 NOT NULL,
 source_version NUMBER(19),
 input_hash VARCHAR2(64),
 model VARCHAR2(64),
 dimensions NUMBER(10),
 vector_json CLOB,
 lease_owner VARCHAR2(64),
 lease_until NUMBER(19),
 CONSTRAINT search_uv_revision CHECK (revision >= 0),
 CONSTRAINT search_uv_lease CHECK (
   (lease_owner IS NULL AND lease_until IS NULL)
   OR (lease_owner IS NOT NULL AND lease_until IS NOT NULL)),
 CONSTRAINT search_uv_cache CHECK (
   (source_version IS NULL AND input_hash IS NULL AND model IS NULL
    AND dimensions IS NULL AND vector_json IS NULL)
   OR (source_version IS NOT NULL AND source_version >= 0 AND input_hash IS NOT NULL
       AND model IS NOT NULL AND dimensions IS NOT NULL
       AND dimensions = 1536 AND vector_json IS NOT NULL))
);

CREATE TABLE search_store_vector (
 store_id VARCHAR2(64) PRIMARY KEY,
 source_version NUMBER(19) NOT NULL,
 input_hash VARCHAR2(64) NOT NULL,
 model VARCHAR2(64) NOT NULL,
 dimensions NUMBER(10) NOT NULL,
 vector_json CLOB NOT NULL,
 CONSTRAINT search_sv_version CHECK (source_version >= 0),
 CONSTRAINT search_sv_dimensions CHECK (dimensions = 1536)
);

INSERT INTO search_user_vector
 (user_id,revision,source_version,input_hash,model,dimensions,vector_json,lease_owner,lease_until)
SELECT ids.user_id, COALESCE(r.revision,v.source_version,0),
 v.source_version,v.input_hash,v.model,v.dimensions,v.vector_json,g.lease_owner,g.lease_until
FROM (SELECT user_id FROM search_vector
      UNION SELECT user_id FROM search_preference_revision
      UNION SELECT user_id FROM search_vector_generation) ids
LEFT JOIN search_vector v ON v.user_id=ids.user_id
LEFT JOIN search_preference_revision r ON r.user_id=ids.user_id
LEFT JOIN search_vector_generation g ON g.user_id=ids.user_id;

-- Copy only embeddings of the current description/model/dimension.
-- Missing or stale embeddings are regenerated by v2; source documents stay in store.
INSERT INTO search_store_vector
 (store_id,source_version,input_hash,model,dimensions,vector_json)
SELECT store_id,source_version,input_hash,vector_model,vector_dimensions,vector_json
FROM search_store_projection
WHERE vector_json IS NOT NULL AND vector_model IS NOT NULL
 AND vector_dimensions=1536 AND vector_hash=input_hash;

ALTER TABLE search_intent ADD (consent_version NUMBER(19));
UPDATE search_intent i SET consent_version=COALESCE(
 (SELECT MAX(c.resource_version) FROM search_consent c WHERE c.intent_id=i.id),
 i.resource_version);
ALTER TABLE search_intent MODIFY (consent_version NOT NULL);
ALTER TABLE search_intent ADD CONSTRAINT search_intent_consent CHECK (
 status <> 'ACTIVE' OR (consent_at > 0 AND consent_version=resource_version));

ALTER TABLE search_work ADD (
 event_id VARCHAR2(64), job_id VARCHAR2(64), slot_id VARCHAR2(64),
 publication_version NUMBER(19));

-- Keep the public job ID even though the old queue had a separate internal ID.
UPDATE search_work w SET (event_id,job_id,slot_id,publication_version) = (
 SELECT j.event_id,j.job_id,j.slot_id,j.publication_version
 FROM search_match_job j
 WHERE j.event_id=JSON_VALUE(w.payload,'$.eventId' RETURNING VARCHAR2(64)))
WHERE w.kind='SLOT';

-- Preserve event identity even if a completed queue row was previously removed.
INSERT INTO search_work
 (id,kind,payload,status,attempts,available_at,event_id,job_id,slot_id,publication_version)
SELECT j.job_id,'SLOT',
 JSON_OBJECT('eventId' VALUE j.event_id,'slotId' VALUE j.slot_id,
             'publicationVersion' VALUE j.publication_version NULL ON NULL RETURNING CLOB),
 j.status,0,0,j.event_id,j.job_id,j.slot_id,j.publication_version
FROM search_match_job j
WHERE NOT EXISTS (SELECT 1 FROM search_work w WHERE w.event_id=j.event_id);

ALTER TABLE search_work ADD CONSTRAINT search_work_event_uq UNIQUE(event_id);
ALTER TABLE search_work ADD CONSTRAINT search_work_job_uq UNIQUE(job_id);
ALTER TABLE search_work ADD CONSTRAINT search_work_slot CHECK (
 (kind='SLOT' AND event_id IS NOT NULL AND job_id IS NOT NULL AND slot_id IS NOT NULL)
 OR (kind<>'SLOT' AND event_id IS NULL AND job_id IS NULL
     AND slot_id IS NULL AND publication_version IS NULL));
COMMIT;

-- Read-only reconciliation. Application must stay stopped for a consistent snapshot.
SELECT 'user_state' AS check_name,
 (SELECT COUNT(*) FROM search_user_vector) AS actual,
 (SELECT COUNT(*) FROM (SELECT user_id FROM search_vector
   UNION SELECT user_id FROM search_preference_revision
   UNION SELECT user_id FROM search_vector_generation)) AS expected FROM dual;
SELECT 'slot_jobs' AS check_name,
 (SELECT COUNT(*) FROM search_work WHERE kind='SLOT') AS actual,
 (SELECT COUNT(*) FROM search_match_job) AS expected FROM dual;
SELECT COUNT(*) AS invalid_active_consent FROM search_intent
 WHERE status='ACTIVE' AND (consent_at<=0 OR consent_version<>resource_version);

